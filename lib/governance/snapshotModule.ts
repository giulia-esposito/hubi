import type { RegistrySnapshot } from "./registry.ts";

/** The exact text of lib/governance/registrySnapshot.ts for a snapshot, so a sync and its check agree byte for byte. */
export function renderSnapshotModule(snapshot: RegistrySnapshot): string {
  return (
    `import type { RegistrySnapshot } from "./registry.ts";\n\n` +
    `// Generated by scripts/sync-registry.ts from config/governance/registry-export.csv. Do not edit by hand.\n` +
    `export const REGISTRY_SNAPSHOT: RegistrySnapshot = ${JSON.stringify(snapshot, null, 2)};\n`
  );
}
